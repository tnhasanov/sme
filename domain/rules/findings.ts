export interface CommentaryInput {
  ratios: Record<string, ExplainedMetric>;
  previousRatios?: Record<string, number | null>;
  salesGrowthPct?: number | null;
  ebitdaGrowthPct?: number | null;
  repayment?: RepaymentCapacityResult;
  crossChecks: CrossCheckResult[];
  refinancing?: RefinancingAnalysis;
}

/** Deterministic sentences an underwriter would otherwise type by hand. */
export function generateCommentary(input: CommentaryInput): string[] {
  const lines: string[] = [];
  const r = input.ratios;

  if (input.salesGrowthPct !== null && input.salesGrowthPct !== undefined) {
    if (input.ebitdaGrowthPct !== null && input.ebitdaGrowthPct !== undefined) {
      if (input.salesGrowthPct > 0.1 && input.ebitdaGrowthPct < input.salesGrowthPct * 0.6) {
        lines.push(
          `Satış ${pct(input.salesGrowthPct)} artdığı halda EBITDA yalnız ${pct(
            input.ebitdaGrowthPct,
          )} artıb — marja sıxılması müşahidə olunur.`,
        );
      } else if (input.salesGrowthPct > 0.1) {
        lines.push(
          `Satış ${pct(input.salesGrowthPct)}, EBITDA isə ${pct(input.ebitdaGrowthPct)} artıb — artım rentabelliyi qoruyur.`,
        );
      } else if (input.salesGrowthPct < -0.05) {
        lines.push(`Satış ${pct(Math.abs(input.salesGrowthPct))} azalıb — gəlir bazasının dayanıqlığı yoxlanılmalıdır.`);
      }
    }
  }

  const prev = input.previousRatios ?? {};
  const trend = (key: string, label: string, unit: 'DAYS' | 'TIMES' | 'PERCENT') => {
    const cur = r[key]?.value;
    const old = prev[key];
    if (cur === null || cur === undefined || old === null || old === undefined) return;
    const f = (v: number) => (unit === 'DAYS' ? `${v.toFixed(0)} gün` : unit === 'PERCENT' ? pct(v) : `${v.toFixed(2)}x`);
    if (Math.abs(cur - old) / Math.max(Math.abs(old), 0.0001) > 0.15) {
      lines.push(`${label} ${f(old)}-dən ${f(cur)}-ə dəyişib.`);
    }
  };

  trend('receivableDays', 'Debitor borcların dövretmə müddəti', 'DAYS');
  trend('inventoryDays', 'Ehtiyatların dövretmə müddəti', 'DAYS');
  trend('debtToEbitda', 'Borc / EBITDA nisbəti', 'TIMES');
  trend('currentRatio', 'Cari likvidlik əmsalı', 'TIMES');

  const rc = input.repayment;
  if (rc) {
    if (!rc.hasCapacity) {
      lines.push(
        `Bəyan edilən mənfəətliliyə baxmayaraq, əməliyyat pul axını təklif olunan strukturu dəstəkləmək üçün kifayət etmir (aylıq kəsir ${fmt(
          Math.abs(rc.headroomMonthly),
        )} AZN).`,
      );
    } else if (rc.dscrAfter !== null) {
      lines.push(
        `Əməliyyatdan sonrakı borc xidməti örtüyü ${rc.dscrAfter.toFixed(2)}x təşkil edir; aylıq ehtiyat ${fmt(
          rc.headroomMonthly,
        )} AZN-dir.`,
      );
    }
  }

  const equityCheck = input.crossChecks.find((c) => c.key === 'EQUITY_RECONCILIATION');
  if (equityCheck && !equityCheck.passed && equityCheck.difference > 0) {
    lines.push(
      `Bağlanış kapitalı bölüşdürülməmiş mənfəət və təsdiqlənmiş sahibkar qoyuluşlarının izah etdiyindən ${fmt(
        equityCheck.difference,
      )} AZN çoxdur.`,
    );
  }

  const salesCash = input.crossChecks.find((c) => c.key === 'SALES_TO_CASH');
  if (salesCash && !salesCash.passed && salesCash.difference < 0) {
    lines.push(
      `Uçot artımı eyni güclü nağd yaratmaya çevrilmir: satışdan gözlənilən daxilolmalarla faktiki daxilolmalar arasında ${fmt(
        Math.abs(salesCash.difference),
      )} AZN fərq var.`,
    );
  }

  const ref = input.refinancing;
  if (ref?.instalmentRepaymentShare !== null && ref?.instalmentRepaymentShare !== undefined) {
    if (ref.instalmentRepaymentShare <= 0.5) {
      lines.push(
        `Əvvəlki kreditlərin yalnız ${pct(
          ref.instalmentRepaymentShare,
        )} hissəsi aylıq ödənişlərlə bağlanıb — qalan hissə yeni kreditlər hesabına örtülüb.`,
      );
    }
  }

  return lines;
}
